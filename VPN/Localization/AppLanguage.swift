import Foundation

/// In-app language. Russian is the default so the prototype opens translated.
enum AppLanguage {
    static let storageKey = "velvet.language"
    static let en = "en"
    static let ru = "ru"

    static var code: String {
        let stored = UserDefaults.standard.string(forKey: storageKey)
        return stored == en ? en : ru
    }
}

func ui(_ text: String) -> String {
    if AppLanguage.code == AppLanguage.en {
        return VelvetCopy.ruToEn[text] ?? text
    }
    return VelvetCopy.enToRu[text] ?? text
}

func uiFormat(_ english: String, _ args: CVarArg...) -> String {
    let template = ui(english)
    return String(format: template, locale: Locale(identifier: AppLanguage.code), arguments: args)
}

func uiPlace(_ name: String) -> String {
    ui(name.withoutEmoji.replacingOccurrences(of: "SMART-", with: ""))
}

func uiTraffic(_ text: String) -> String {
    if let match = text.wholeMatch(of: /(\d+) GB left/), let amount = Int(match.1) {
        return uiFormat("%lld GB left", amount)
    }
    return ui(text)
}

/// Both languages, so search still finds a place after the label changes.
func uiVariants(_ text: String) -> String {
    let russian = VelvetCopy.enToRu[text] ?? text
    let english = VelvetCopy.ruToEn[text] ?? text
    return "\(text) \(russian) \(english)"
}

